#!/usr/bin/env python3
"""Update host/stubs/stubs.S from the link errors of resonance_host.

An undefined reference gains a stub. A multiple definition loses its stub, because host/ now
implements the routine. Repeat until the link succeeds:

    cmake --build build-host 2>&1 | python3 -I host/stubs/gen-stubs.py build-host host/stubs/stubs.S

A symbol that no archive calls through the PLT is data, and its stub is a zeroed block. A stub
returns zero unless its line names another value, which survives regeneration:

    STUB sceSifSyncIop, 1
"""
import pathlib
import re
import subprocess
import sys

HEADER = '''\
// Generated by host/stubs/gen-stubs.py. Each stub is a routine host/ does not implement yet. It
// reports its first call through HostUnimplemented() and returns its value, zero by default, with
// every other return register zeroed.

    .macro STUB name, value=0
    .text
    .globl \\name
    .type \\name, @function
\\name:
    sub $8, %rsp
    lea .Lname\\@(%rip), %rdi
    lea .Lreported\\@(%rip), %rsi
    call HostUnimplemented
    add $8, %rsp
    mov $\\value, %rax
    xor %edx, %edx
    pxor %xmm0, %xmm0
    pxor %xmm1, %xmm1
    ret
    .size \\name, . - \\name
    .section .rodata.str1.1, "aMS", @progbits, 1
.Lname\\@:
    .asciz "\\name"
    .bss
.Lreported\\@:
    .byte 0
    .endm

    .macro DATA_STUB name
    .bss
    .balign 64
    .globl \\name
    .type \\name, @object
\\name:
    .zero 256
    .size \\name, 256
    .endm

'''


def called_symbols(build_dir: pathlib.Path) -> set[str]:
    archives = sorted(str(path) for path in build_dir.rglob('*.a'))
    dump = subprocess.run(['objdump', '-r', *archives], capture_output=True, text=True,
                          check=True).stdout
    return set(re.findall(r'R_X86_64_PLT32\s+([^\s+-]+)', dump))


def main() -> None:
    build_dir = pathlib.Path(sys.argv[1])
    stubs_path = pathlib.Path(sys.argv[2])
    log = sys.stdin.read()
    stubs = {}
    if stubs_path.exists():
        stubs = {
            name: (kind, f', {value}' if value else '')
            for kind, name, value in re.findall(r'^(STUB|DATA_STUB) ([^\s,]+)(?:, (\S+))?$',
                                                stubs_path.read_text(), re.M)
        }
    undefined = set(re.findall(r"undefined reference to `([^']+)'", log)) - stubs.keys()
    called = called_symbols(build_dir) if undefined else set()
    for name in undefined:
        stubs[name] = ('STUB' if name in called else 'DATA_STUB', '')
    for name in re.findall(r"multiple definition of `([^']+)'", log):
        stubs.pop(name, None)
    lines = ''.join(f'{kind} {name}{value}\n' for name, (kind, value) in sorted(stubs.items()))
    stubs_path.write_text(HEADER + lines + '\n    .section .note.GNU-stack, "", @progbits\n')
    print(f'{len(stubs)} stubs, {len(undefined)} added', file=sys.stderr)


if __name__ == '__main__':
    main()
